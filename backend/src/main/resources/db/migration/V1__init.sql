-- Baseline schema. Databases created earlier by Hibernate are marked as V1 (baseline-on-migrate) and skip this file.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL UNIQUE,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    phone         VARCHAR(255),
    role          VARCHAR(255) NOT NULL CHECK (role IN ('ROLE_CLIENT', 'ROLE_PROVIDER')),
    created_at    TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE provider_profiles (
    user_id         BIGINT PRIMARY KEY REFERENCES users (id),
    specialty       VARCHAR(255),
    bio             TEXT,
    address         VARCHAR(255),
    price_per_visit DOUBLE PRECISION
);

CREATE TABLE appointments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        BIGINT NOT NULL REFERENCES users (id),
    provider_id      BIGINT NOT NULL REFERENCES users (id),
    appointment_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    status           VARCHAR(255) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    notes            TEXT
);

CREATE TABLE messages (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id      BIGINT NOT NULL REFERENCES users (id),
    receiver_id    BIGINT NOT NULL REFERENCES users (id),
    appointment_id BIGINT REFERENCES appointments (id),
    content        TEXT NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE
);
